export type Direction = 'toRoman' | 'toDecimal';

export type InputMode = 'mc' | 'keypad';

export type SoundType = 'correct' | 'wrong' | 'star';

/** A curriculum level, as served by the curriculum remote function. */
export interface Concept {
	id: number;
	title: string;
	shortName: string;
	tag: string;
	description: string;
	tip: string;
	/** Whether the keypad needs the vinculum (roof bar) keys. */
	hasVinculum?: boolean;
	/** Trusted, authored HTML for the lesson modal. */
	lessonHtml: string;
}

export interface Question {
	conceptId: number;
	value: number;
	roman: string;
	direction: Direction;
	promptText: string;
	correctTarget: string;
}

export interface LevelProgress {
	stars: number;
	/** 0–4; the fifth correct answer awards a star and resets this to 0. */
	progress: number;
	streak: number;
}

/** The shape persisted by a {@link ProgressRepository}. */
export interface SavedState {
	currentLevelId: number;
	mode: InputMode;
	soundEnabled?: boolean;
	levels: Record<number, LevelProgress>;
}

export interface BreakdownPart {
	placeValue: number;
	digit: number;
	roman: string;
}

export type FeedbackKind = 'success' | 'error' | 'hint';

export interface Feedback {
	kind: FeedbackKind;
	icon: string;
	title: string;
	/** Trusted HTML generated by the app (never user input). */
	messageHtml: string;
	breakdown: BreakdownPart[];
}
